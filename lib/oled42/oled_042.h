// Минимальный драйвер OLED 0.42" 72x40 по I2C (для контроллеров класса SSD1306/SH1106).
// Слой абстракции для дисплеев с постраничной адресацией и аппаратным смещением столбцов.
// Предоставляет: инициализацию, очистку, вывод текста/unsigned-чисел шрифтом 5x7 и полное обновление экрана.

#pragma once
#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"
#include "driver/i2c.h"

typedef struct {
    // Конфигурация I2C-шины и геометрии конкретного OLED-модуля.
    i2c_port_t port;        // Номер порта I2C: I2C_NUM_0 / I2C_NUM_1.
    int sda_io;             // GPIO, подключённый к линии SDA.
    int scl_io;             // GPIO, подключённый к линии SCL.
    uint32_t clk_hz;        // Частота шины I2C.
    uint8_t i2c_addr;       // 7-битный I2C-адрес дисплея (обычно 0x3C или 0x3D).
    int width;              // Видимая ширина экрана в пикселях, например 72.
    int height;             // Видимая высота экрана в пикселях, например 40.
    int col_offset;         // Аппаратное смещение окна по столбцам внутри памяти на 128 столбцов.
    int row_offset;         // Необязательное вертикальное смещение по строкам (в пикселях), обычно 0.
    bool use_sh1106_pump;   // Если true, после инициализации включается DC-DC SH1106 командами 0xAD, 0x8B.
} oled042_cfg_t;

// Инициализирует шину I2C (с установкой драйвера) и сам дисплей в режиме постраничной адресации.
// Также выделяет и очищает локальный VRAM-буфер. При необходимости выполняет сканирование I2C и пишет найденные устройства в лог.
esp_err_t oled042_init(const oled042_cfg_t *cfg, bool scan_i2c);

// Очищает локальный буфер кадра, заполняя его чёрным цветом.
void oled042_clear(void);

// Отправляет весь буфер кадра на дисплей постранично.
esp_err_t oled042_update(void);

// Простой API для вывода текста и unsigned-чисел (подмножество ASCII, глифы 5x7).
void oled042_draw_text(int x, int y, const char *s);
void oled042_draw_uint(int x, int y, unsigned v);

// Заполняет буфер тестовым паттерном для быстрой проверки геометрии, смещения и контраста.
void oled042_test_pattern(void);

// Позволяет на лету изменить смещение столбцов без повторной инициализации.
// Удобно для подстройки модулей 0.42", у которых видимая область сдвинута внутри памяти контроллера.
void oled042_set_col_offset(int offset);
